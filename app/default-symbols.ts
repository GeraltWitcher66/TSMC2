export const normalizeSymbol = (value: string) =>
  value
    .replace(/ك/g, "ک")
    .replace(/ي/g, "ی")
    .replace(/[\u200c\u200f\ufeff]/g, "")
    .replace(/\s+/g, " ")
    .trim();

export const defaultSymbols = Array.from(
  new Set(rawSymbols.split("\n").map(normalizeSymbol).filter(Boolean)),
);
